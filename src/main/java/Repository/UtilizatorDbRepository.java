package Repository;

import domain.Utilizator;
import domain.Validator;
import exceptions.RepoException;
import util.paging.Page;
import util.paging.Pageable;

import java.sql.*;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

public class UtilizatorDbRepository implements PagingRepository<Integer, Utilizator> {
    private Validator<Utilizator> validator;
    private String url;
    private String user;
    private String password;

    /**
     * Constructs a new UtilizatorDbRepository.
     *
     * @param url the database connection URL
     * @param user the database username
     * @param password the database password
     * @param validator the validator for Utilizator entities
     */
    public UtilizatorDbRepository(String url, String user, String password, Validator<Utilizator> validator) {
        this.url = url;
        this.user = user;
        this.password = password;
        this.validator = validator;
    }

    /**
     * Get a user by ID.
     *
     * @param id the ID of the user to find
     * @return an Optional with the found user, or empty if not found
     * @throws IllegalArgumentException if the id is null
     * @throws RepoException if there is a database error
     */
    @Override
    public Optional<Utilizator> findOne(Integer id) {
        if(id == null) {
            throw new IllegalArgumentException("Id ul nu poate fi null!");
        }
        String sql = "SELECT id,first_name, last_name FROM users WHERE id = ?";
        try (Connection connection = DriverManager.getConnection(url, user, password);
             PreparedStatement statement = connection.prepareStatement(sql)){

            statement.setInt(1, id);
            try (ResultSet resultSet = statement.executeQuery()){
                if(resultSet.next()) {
                    String firstName = resultSet.getString("first_name");
                    String lastName = resultSet.getString("last_name");
                    return  Optional.of(new Utilizator(id, firstName, lastName));
                }
            }
            return Optional.empty();
        } catch (SQLException e){
            throw new RepoException("Eroare la DB (findOne user): " + e.getMessage());
        }
    }

    /**
     * Get all users from the database with their loaded friendships.
     *
     * @return an Iterable of all users
     * @throws RepoException if there is a database error
     */
    @Override
    public Iterable<Utilizator> findAll() {
        List<Utilizator> users = new ArrayList<>();
        String sqlUsers = "SELECT id, first_name, last_name FROM users";
        String sqlFriendships = "SELECT id1, id2 FROM friendships";

        try (Connection connection = DriverManager.getConnection(url,user,password);
             PreparedStatement stmtUsers = connection.prepareStatement(sqlUsers);
             ResultSet rsUsers = stmtUsers.executeQuery()){

            while(rsUsers.next()){
                int id = rsUsers.getInt("id");
                String firstName = rsUsers.getString("first_name");
                String lastName = rsUsers.getString("last_name");
                users.add(new Utilizator(id, firstName, lastName));
            }

            try (PreparedStatement stmtFriends = connection.prepareStatement(sqlFriendships);
                 ResultSet rsFriends = stmtFriends.executeQuery()){
                while (rsFriends.next()){
                    int id1 = rsFriends.getInt("id1");
                    int id2 = rsFriends.getInt("id2");
                    Utilizator u1 = users.stream().filter(u -> u.getId() == id1).findFirst().orElse(null);
                    Utilizator u2 = users.stream().filter(u -> u.getId() == id2).findFirst().orElse(null);
                    if(u1 != null && u2 != null) {
                        u1.addPrieten(u2);
                        u2.addPrieten(u1);
                    }
                }
            }
            return users;
        } catch (SQLException e) {
            throw new RepoException("Eroare la DB (findAll users): " + e.getMessage());
        }
    }

    /**
     * Saves a new user to the database with ID generated by the database
     *
     * @param entity the user entity to save
     * @return null if the user was successfully saved, or the entity itself if it already exists
     * @throws IllegalArgumentException if the entity is null
     * @throws RepoException if there is a database error
     */
    @Override
    public Utilizator save(Utilizator entity) {
        if(entity == null) {
            throw new IllegalArgumentException("Entitatea nu poate fi null!");
        }
        validator.validate(entity);
        if (entity.getId() != null && findOne(entity.getId()).isPresent()) {
            return entity;
        }
        String sql = "INSERT INTO users (first_name, last_name) VALUES (?, ?)";
        try (Connection connection = DriverManager.getConnection(url,user,password);
             PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)){

            statement.setString(1, entity.getPrenume());
            statement.setString(2, entity.getNume());
            statement.executeUpdate();
            try (ResultSet generatedKeys = statement.getGeneratedKeys()){
                if (generatedKeys.next()) {
                    entity.setId(generatedKeys.getInt(1));
                }
            }
            return null;
        } catch (SQLException e) {
            throw new RepoException("Eroare la DB (save user): " + e.getMessage());
        }
    }

    /**
     * Deletes a user from the database by ID.
     *
     * @param id the ID of the user to delete
     * @return an Optional containing the deleted user, or empty if no user was found
     * @throws IllegalArgumentException if the id is null
     * @throws RepoException if there is a database error
     */
    @Override
    public Optional<Utilizator> delete(Integer id) {
        if (id == null) {
            throw new IllegalArgumentException("Id ul nu poate fi null!");
        }
        Optional<Utilizator> userToDelete = findOne(id);
        if (userToDelete.isEmpty()) {
            return Optional.empty();
        }
        String sql = "DELETE FROM users WHERE id = ?";
        try (Connection connection = DriverManager.getConnection(url,user,password);
             PreparedStatement statement = connection.prepareStatement(sql)){

            statement.setInt(1, id);
            statement.executeUpdate();
            return userToDelete;
        } catch (SQLException e) {
            throw new RepoException("Eroare la DB (delete user): " + e.getMessage());
        }
    }

    /**
     * Updates an existing user in the database.
     *
     * @param entity the user entity with updated fields
     * @return an empty Optional if updated successfully, or an Optional containing the entity if the ID was not found
     * @throws IllegalArgumentException if the entity is null
     * @throws RepoException if there is a database error
     */
    @Override
    public Optional<Utilizator> update(Utilizator entity) {
        if (entity == null) {
            throw new IllegalArgumentException("Entitatea nu poate fi null!");
        }
        validator.validate(entity);
        String sql = "UPDATE users SET first_name = ?, last_name = ? WHERE id = ?";
        try (Connection connection = DriverManager.getConnection(url,user,password);
             PreparedStatement statement = connection.prepareStatement(sql)){
            statement.setString(1, entity.getPrenume());
            statement.setString(2, entity.getNume());
            statement.setInt(3, entity.getId());
            int affectedRow = statement.executeUpdate();
            if (affectedRow > 0) {
                return Optional.empty();
            }
            return Optional.of(entity);
        } catch (SQLException e) {
            throw new RepoException("Eroare la DB (update user): " + e.getMessage());
        }
    }

    @Override
    public Page<Utilizator> findAllOnPage(Pageable pageable) {
        if(pageable == null) {
            throw new IllegalArgumentException("Pageable nu poate fi null!");
        }

        List<Utilizator> users = new ArrayList<>();
        String countSql = "SELECT COUNT(*) AS count FROM users";
        String pageSql = "SELECT id, first_name, last_name FROM users ORDER BY id LIMIT ? OFFSET ?";
        try (Connection connection = DriverManager.getConnection(url, user, password)){
            int totalCount = 0;
            try(PreparedStatement countStmt = connection.prepareStatement(countSql);
                ResultSet countRs = countStmt.executeQuery()){
                if(countRs.next()){
                    totalCount = countRs.getInt("count");
                }
            }

            try(PreparedStatement pageStmt = connection.prepareStatement(pageSql)){
                pageStmt.setInt(1, pageable.getPageSize());
                pageStmt.setInt(2, pageable.getPageNumber() *  pageable.getPageSize());
                try(ResultSet rs = pageStmt.executeQuery()){
                    while (rs.next()){
                        int id = rs.getInt("id");
                        String firstName = rs.getString("first_name");
                        String lastName = rs.getString("last_name");
                        users.add(new Utilizator(id, firstName, lastName));
                    }
                }
            }
            return new Page<>(users,totalCount);
        } catch(SQLException e) {
            throw new RepoException("Eroare la DB (findAllOnPage users): " + e.getMessage());
        }
    }
}
